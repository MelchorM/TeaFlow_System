CREATE TABLE IF NOT EXISTS tf_meta (name VARCHAR(60) PRIMARY KEY, value VARCHAR(200) NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_sessions (
 session_id VARCHAR(128) PRIMARY KEY, expires BIGINT UNSIGNED NOT NULL, data MEDIUMTEXT NOT NULL, INDEX(expires)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(200) NOT NULL, role ENUM('customer','cashier','kitchen','admin') NOT NULL DEFAULT 'customer',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_products (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, reference_id INT UNSIGNED NULL UNIQUE, name VARCHAR(100) NOT NULL,
 category VARCHAR(100) NOT NULL, image VARCHAR(240) NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
 archived BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_variants (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id INT UNSIGNED NOT NULL, size ENUM('Small','Large') NOT NULL,
 price_cents INT UNSIGNED NOT NULL, UNIQUE KEY(product_id,size),
 FOREIGN KEY(product_id) REFERENCES tf_products(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_ingredients (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE, unit VARCHAR(30) NOT NULL,
 stock_milli BIGINT UNSIGNED NOT NULL DEFAULT 0, low_milli BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_recipes (
 variant_id INT UNSIGNED NOT NULL, ingredient_id INT UNSIGNED NOT NULL, amount_milli BIGINT UNSIGNED NOT NULL,
 option_basis ENUM('fixed','sugar','ice') NOT NULL DEFAULT 'fixed',
 PRIMARY KEY(variant_id,ingredient_id), FOREIGN KEY(variant_id) REFERENCES tf_variants(id),
 FOREIGN KEY(ingredient_id) REFERENCES tf_ingredients(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_addons (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL UNIQUE, price_cents INT UNSIGNED NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, ingredient_id INT UNSIGNED NOT NULL, amount_milli BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY(ingredient_id) REFERENCES tf_ingredients(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_orders (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, request_key CHAR(36) NOT NULL UNIQUE, request_hash CHAR(64) NOT NULL,
 tracking_token CHAR(36) NOT NULL UNIQUE, customer_id INT UNSIGNED NULL, customer_name VARCHAR(80) NOT NULL,
 actor VARCHAR(100) NOT NULL, source ENUM('web','cashier') NOT NULL,
 status ENUM('unpaid','queued','preparing','ready','completed') NOT NULL DEFAULT 'unpaid',
 total_cents INT UNSIGNED NOT NULL, paid_by INT UNSIGNED NULL, paid_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(customer_id) REFERENCES tf_users(id), FOREIGN KEY(paid_by) REFERENCES tf_users(id), INDEX(status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_order_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id INT UNSIGNED NOT NULL, product_name VARCHAR(100) NOT NULL,
 size VARCHAR(20) NOT NULL, sugar TINYINT UNSIGNED NOT NULL, ice VARCHAR(20) NOT NULL,
 quantity INT UNSIGNED NOT NULL, unit_cents INT UNSIGNED NOT NULL, addons JSON NOT NULL,
 FOREIGN KEY(order_id) REFERENCES tf_orders(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_requirements (
 order_id INT UNSIGNED NOT NULL, ingredient_id INT UNSIGNED NOT NULL, amount_milli BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(order_id,ingredient_id), FOREIGN KEY(order_id) REFERENCES tf_orders(id),
 FOREIGN KEY(ingredient_id) REFERENCES tf_ingredients(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_stock_movements (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ingredient_id INT UNSIGNED NOT NULL, order_id INT UNSIGNED NULL,
 user_id INT UNSIGNED NULL, delta_milli BIGINT NOT NULL, reason VARCHAR(200) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE KEY(order_id,ingredient_id),
 FOREIGN KEY(ingredient_id) REFERENCES tf_ingredients(id), FOREIGN KEY(order_id) REFERENCES tf_orders(id),
 FOREIGN KEY(user_id) REFERENCES tf_users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tf_order_events (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id INT UNSIGNED NOT NULL, type VARCHAR(20) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY(order_id) REFERENCES tf_orders(id)
) ENGINE=InnoDB;
